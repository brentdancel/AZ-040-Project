# Parameters required input
[CmdletBinding()]
param (
    [string]$FirstName,
    [string]$LastName,
    [string]$Department
)

# Check if the Active Directory module is installed, and install it if not
if (Get-Module -ListAvailable -Name ActiveDirectory) {
    Write-Verbose -Message "The ActiveDirectory module is already installed." -Verbose
}
else {
    $operatingSystem = Get-CimInstance -ClassName Win32_OperatingSystem -ErrorAction Stop
    if ($operatingSystem.ProductType -eq 1) {
        $installation = Add-WindowsCapability -Online -Name Rsat.ActiveDirectory.DS-LDS.Tools~~~~0.0.1.0 -ErrorAction Stop
        if ($installation.State -ne 'Installed') {
            throw "Failed to install the Active Directory RSAT capability."
        }
    }
    else {
        $installation = Install-WindowsFeature -Name RSAT-AD-PowerShell -ErrorAction Stop
        if (-not $installation.Success) {
            throw "Failed to install the Active Directory PowerShell feature."
        }
    }
}

# Prompting for user input if parameters are not provided
if (-not $FirstName) {
    $FirstName = Read-Host -Prompt "Please enter the new user's first name"
}
if (-not $LastName) {
    $LastName = Read-Host -Prompt "Please enter the new user's last name"
}
if (-not $Department) {
    $Department = Read-Host -Prompt "Please enter the new user's department"
}

# Wrapping main code within the try/catch block to handle any errors that may occur during execution
# Username is generated by using the first name
# CHANGE USERNAME GENERATION BASED ON ORGANIZATIONAL NEEDS
try {
    # Checks if the username already exists in Active Directory
    $userName = $FirstName
    $i = 2 
    while (Get-ADUser -Filter "SamAccountName -eq '$userName'") {
        Write-Host "The username [$userName] already exists. Generating a new username..." -ForegroundColor Yellow
        $userName = "$FirstName$i"
        $i++
    }
    Write-Host "The username for the new user will be: $userName" -ForegroundColor Green

# The if/elseif statements checks for the OU and group
# If the OU or group does not exist, it will throw an error and stop the script
    if (-not ($ou = Get-ADOrganizationalUnit -Filter "Name -eq '$Department'")) {
        throw "The Active Directory OU for department $($Department) could not be found."
    } elseif (-not (Get-ADGroup -Filter "Name -eq '$Department'")){
        throw "The group [$($Department)] does not exist."
    }

<# This generates a randomly generated password for the initial account creation
You can change the minimum and maximum characters, depending on organizational needs #>
    Add-Type -AssemblyName 'System.Web'
    $password = [System.Web.Security.Membership]::GeneratePassword((Get-Random -Minimum 8 -Maximum 33), 3)
    $secPw = ConvertTo-SecureString -String $password -AsPlainText -Force


# After getting all the parameters, we can now create the user account and add it to the desired group
    $newUserParams = @{
        Name = "$FirstName $LastName"
        GivenName = $FirstName
        Surname = $LastName
        SamAccountName = $userName
        UserPrincipalName = "$userName@$env:USERDNSDOMAIN"
        AccountPassword = $secPw
        ChangePasswordAtLogon = $true
        # Create the account as disabled initially
        Enabled = $false
        Department = $Department
        Path = $ou.DistinguishedName
    }
    New-ADuser @newUserParams
    Add-ADGroupMember -Identity $Department -Members $userName

# HTML output for the user onboarding information
    $html = @"
        <!DOCTYPE html>
        <head>
        <meta charset="UTF-8">
        <meta name="viewport" content="width=device-width, initial-scale=1.0">
        <title>User Onboarding</title>

        <style>
            body {
                font-family: Arial, sans-serif;
                background-color: #9fa2b1;
                margin: 0;
                padding: 20px;
                text-align: center;
            }

            h1 {
                color: #333;
            }

            h2 {
                color: #e41111;
            }

            p {
                font-size: 16px;
                color: #555;
            }

            table {
                width: 80%;
                max-width: 700px;
                margin: 20px auto;
                border-collapse: collapse;
                background-color: #ffffff;
                text-align: left;
                box-shadow: 0 2px 8px rgba(0, 0, 0, 0.15);
            }

            th, td {
                padding: 12px 15px;
                border: 1px solid #ccc;
                font-size: 16px;
            }

            th {
                background-color: #333;
                color: #ffffff;
                text-align: left;
            }

            td:first-child {
                width: 35%;
                font-weight: normal;
                background-color: #f2f2f2;
            }

            td strong {
                color: #222;
            }

            h2 {
                font-size: 18px;
                margin-top: 25px;
            }

            @media (max-width: 600px) {
                table {
                    width: 100%;
                }

                th, td {
                    padding: 10px;
                    font-size: 14px;
                    overflow-wrap: anywhere;
                }
            }
        </style>
    </head>

    <body>
        <h1>User Onboarding</h1>

        <p>
            A new user account has been created for
            <strong>$FirstName $LastName</strong>.
        </p>

        <table>
            <thead>
                <tr>
                    <th>Setting</th>
                    <th>Information</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>First Name</td>
                    <td><strong>$FirstName</strong></td>
                </tr>
                <tr>
                    <td>Last Name</td>
                    <td><strong>$LastName</strong></td>
                </tr>
                <tr>
                    <td>Username</td>
                    <td><strong>$userName</strong></td>
                </tr>
                <tr>
                    <td>Temporary Password</td>
                    <td><strong>$password</strong></td>
                </tr>
                <tr>
                    <td>SamAccountName</td>
                    <td><strong>$userName</strong></td>
                </tr>
                <tr>
                    <td>UserPrincipalName</td>
                    <td><strong>$userName@$env:USERDNSDOMAIN</strong></td>
                </tr>
                <tr>
                    <td>Department</td>
                    <td><strong>$Department</strong></td>
                </tr>
                <tr>
                    <td>Organizational Unit (Path)</td>
                    <td><strong>$($ou.DistinguishedName)</strong></td>
                </tr>
            </tbody>
        </table>

        <h2>
            Please ensure the user changes their password upon first login.
        </h2>

        <h2>
            Delete this file after onboarding is complete to maintain security.
        </h2>
    </body>
    </html>
"@

    $html | Out-File -FilePath C:\Users\Public\Documents\UserOnboarding.html -Encoding UTF8
    Start-Process -FilePath "C:\Users\Public\Documents\UserOnboarding.html"

} catch {
    Write-Host "Error: $_.Exception.Message" -ForegroundColor Red
}